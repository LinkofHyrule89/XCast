package com.xcast.android

data class HlsAudio(
    val groupId: String,
    val name: String,
    val uri: String,
    val language: String?,
    val bitrateHint: Int,
)

data class HlsSubtitle(
    val groupId: String,
    val name: String,
    val uri: String,
    val language: String?,
    val autoGenerated: Boolean,
    val closedCaptions: Boolean,
)

data class HlsVideo(
    val uri: String,
    val width: Int,
    val height: Int,
    val bandwidth: Int,
    val codecs: String?,
    val audioGroupId: String?,
)

data class HlsMaster(
    val masterUrl: String,
    val videos: List<HlsVideo>,
    val audios: List<HlsAudio>,
    val subtitles: List<HlsSubtitle>,
)

object HlsMasterParser {
    fun parse(masterUrl: String, body: String): HlsMaster {
        val lines = body.lines()
        val audios = mutableListOf<HlsAudio>()
        val videos = mutableListOf<HlsVideo>()
        val subtitles = mutableListOf<HlsSubtitle>()
        var i = 0
        while (i < lines.size) {
            val line = lines[i].trim()
            if (line.startsWith("#EXT-X-MEDIA:") && line.contains("TYPE=AUDIO")) {
                val attrs = parseAttrs(line.removePrefix("#EXT-X-MEDIA:"))
                val uri = attrs["URI"]?.let { resolve(masterUrl, it) } ?: ""
                if (uri.isNotBlank()) {
                    val group = attrs["GROUP-ID"].orEmpty()
                    val hint = Regex("""(\d{4,})""").find(group)?.groupValues?.get(1)?.toIntOrNull() ?: 0
                    audios += HlsAudio(
                        groupId = group,
                        name = attrs["NAME"] ?: "Audio",
                        uri = uri,
                        language = attrs["LANGUAGE"],
                        bitrateHint = hint,
                    )
                }
            } else if (line.startsWith("#EXT-X-MEDIA:") &&
                (line.contains("TYPE=SUBTITLES") || line.contains("TYPE=CLOSED-CAPTIONS"))
            ) {
                val attrs = parseAttrs(line.removePrefix("#EXT-X-MEDIA:"))
                val uri = attrs["URI"]?.let { resolve(masterUrl, it) }.orEmpty()
                val chars = attrs["CHARACTERISTICS"].orEmpty()
                subtitles += HlsSubtitle(
                    groupId = attrs["GROUP-ID"].orEmpty(),
                    name = attrs["NAME"] ?: "Subtitles",
                    uri = uri,
                    language = attrs["LANGUAGE"],
                    autoGenerated = chars.contains("auto-generated", ignoreCase = true),
                    closedCaptions = line.contains("CLOSED-CAPTIONS") ||
                        chars.contains("public.accessibility.describes-music-and-sound", ignoreCase = true) ||
                        chars.contains("twitter.show-text-when-muted", ignoreCase = true) ||
                        (attrs["NAME"]?.contains("auto", ignoreCase = true) == true),
                )
            } else if (line.startsWith("#EXT-X-STREAM-INF:")) {
                val attrs = parseAttrs(line.removePrefix("#EXT-X-STREAM-INF:"))
                val next = lines.getOrNull(i + 1)?.trim().orEmpty()
                if (next.isNotBlank() && !next.startsWith("#")) {
                    val (w, h) = parseResolution(attrs["RESOLUTION"])
                    videos += HlsVideo(
                        uri = resolve(masterUrl, next),
                        width = w,
                        height = h,
                        bandwidth = attrs["BANDWIDTH"]?.toIntOrNull() ?: 0,
                        codecs = attrs["CODECS"],
                        audioGroupId = attrs["AUDIO"],
                    )
                    i++
                }
            }
            i++
        }
        return HlsMaster(masterUrl, videos, audios, subtitles)
    }

    fun firstMediaUri(playlistUrl: String, body: String): String? {
        for (line in body.lines()) {
            val trimmed = line.trim()
            if (trimmed.isEmpty() || trimmed.startsWith("#")) continue
            return resolve(playlistUrl, trimmed)
        }
        return null
    }

    private fun parseResolution(value: String?): Pair<Int, Int> {
        val parts = value?.split("x") ?: return 0 to 0
        if (parts.size != 2) return 0 to 0
        return (parts[0].toIntOrNull() ?: 0) to (parts[1].toIntOrNull() ?: 0)
    }

    private fun parseAttrs(raw: String): Map<String, String> {
        val out = linkedMapOf<String, String>()
        val regex = Regex("""([A-Z0-9-]+)=("([^"]*)"|[^,]*)""")
        for (m in regex.findAll(raw)) {
            val key = m.groupValues[1]
            val quoted = m.groupValues[3]
            val plain = m.groupValues[2]
            out[key] = quoted.ifBlank { plain }.trim()
        }
        return out
    }

    private fun resolve(masterUrl: String, ref: String): String {
        if (ref.startsWith("http://") || ref.startsWith("https://")) return ref
        return java.net.URI(masterUrl).resolve(ref).toString()
    }
}
